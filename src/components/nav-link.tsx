export function Icon({ name }: { name: NavIcon }) {
  return (
    <svg className="icon" viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d={PATHS[name]} />
    </svg>
  );
}

export function NavLink({
  href,
  children,
  count,
  hot,
  icon,
  dot,
  className,
}: {
  href: string;
  children: React.ReactNode;
  count?: number;
  hot?: boolean;
  icon?: NavIcon;
  /** フォルダの色の点（CSS のクラス名 f-<フォルダ>） */
  dot?: string;
  className?: string;
}) {
  const pathname = usePathname();
  const params = useSearchParams();
  const url = new URL(href, "http://x");
  const active =
    pathname === url.pathname && (url.searchParams.get("folder") ?? "") === (params.get("folder") ?? "");
  return (
    <Link href={href} className={[className, active ? "active" : ""].filter(Boolean).join(" ") || undefined}>
      {icon ? <Icon name={icon} /> : null}
      {dot ? <span className={`dot f-${dot}`} aria-hidden="true" /> : null}
      <span className="nav-label">{children}</span>
      {count ? <span className={hot ? "count hot" : "count"}>{count}</span> : null}
    </Link>
  );
}
